export interface CaptionGroup {
  start: number;
  end: number;
  lastEnd: number;
  words: CaptionWordItem[];
}

export function buildGroups(segments: CaptionSegment[], wordsPerLine: number): CaptionGroup[] {
  const groups: CaptionGroup[] = [];
  const sorted = [...(segments || [])].sort((a, b) => a.start - b.start);

  for (const seg of sorted) {
    let words = seg.words || [];
    if (!words || words.length === 0) {
      const toks = (seg.text || '').split(/\s+/).filter(Boolean);
      if (toks.length === 0) continue;
      const dur = Math.max(0.05, seg.end - seg.start);
      const step = dur / toks.length;
      words = toks.map((t, i) => ({
        w: t,
        s: seg.start + i * step,
        e: seg.start + (i + 1) * step,
        hl: false,
      }));
    }

    const n = wordsPerLine <= 0 ? words.length : wordsPerLine;
    for (let i = 0; i < words.length; i += n) {
      const chunk = words.slice(i, i + n);
      if (chunk.length > 0) {
        groups.push({
          start: chunk[0].s,
          lastEnd: chunk[chunk.length - 1].e,
          end: chunk[chunk.length - 1].e + 0.5,
          words: chunk,
        });
      }
    }
  }

  for (let i = 0; i < groups.length; i++) {
    const nextStart = i + 1 < groups.length ? groups[i + 1].start : Infinity;
    groups[i].end = Math.max(groups[i].start + 0.05, Math.min(nextStart, groups[i].lastEnd + 0.55));
  }

  return groups;
}

export function formatTimecode(sec: number, fps = 30): string {
  if (isNaN(sec) || sec < 0) sec = 0;
  const totalFrames = Math.floor(sec * fps);
  const f = totalFrames % fps;
  const totalSec = Math.floor(sec);
  const s = totalSec % 60;
  const m = Math.floor(totalSec / 60) % 60;
  const h = Math.floor(totalSec / 3600);

  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(h)}:${pad(m)}:${pad(s)}:${pad(f)}`;
}

export function formatDuration(sec: number): string {
  if (isNaN(sec) || sec < 0) sec = 0;
  const s = Math.floor(sec) % 60;
  const m = Math.floor(sec / 60);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(m)}:${pad(s)}`;
}

export function formatSrtTimestamp(seconds: number): string {
  const s = Math.max(0, seconds);
  const ms = Math.floor((s % 1) * 1000);
  const totalSec = Math.floor(s);
  const secs = totalSec % 60;
  const mins = Math.floor(totalSec / 60) % 60;
  const hours = Math.floor(totalSec / 3600);
  const pad = (n: number, w = 2) => String(n).padStart(w, '0');
  return `${pad(hours)}:${pad(mins)}:${pad(secs)},${pad(ms, 3)}`;
}

export function exportSrt(segments: CaptionSegment[], offsetSec = 0): string {
  const sorted = [...(segments || [])].sort((a, b) => a.start - b.start);
  const cues: string[] = [];

  sorted.forEach((seg, index) => {
    const startSec = Math.max(0, seg.start - offsetSec);
    const endSec = Math.max(startSec + 0.1, seg.end - offsetSec);
    const text = (seg.text || '').trim();
    if (!text) return;

    cues.push(`${index + 1}\n${formatSrtTimestamp(startSec)} --> ${formatSrtTimestamp(endSec)}\n${text}\n`);
  });

  return cues.join('\n');
}

function formatAssTime(seconds: number): string {
  const s = Math.max(0, seconds);
  const cs = Math.floor((s % 1) * 100);
  const totalSec = Math.floor(s);
  const secs = totalSec % 60;
  const mins = Math.floor(totalSec / 60) % 60;
  const hours = Math.floor(totalSec / 3600);
  const pad = (n: number, w = 2) => String(n).padStart(w, '0');
  return `${hours}:${pad(mins)}:${pad(secs)}.${pad(cs, 2)}`;
}

function hexToAssColor(hex: string, alpha = 1.0): string {
  const clean = (hex || '#FFFFFF').replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const r = full.substring(0, 2);
  const g = full.substring(2, 4);
  const b = full.substring(4, 6);
  const a = Math.round((1 - Math.max(0, Math.min(1, alpha))) * 255);
  const padHex = (n: number) => n.toString(16).padStart(2, '0').toUpperCase();
  return `&H${padHex(a)}${b}${g}${r}&`.toUpperCase();
}

function hexToAssInlineColor(hex: string): string {
  const clean = (hex || '#FFFFFF').replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const r = full.substring(0, 2);
  const g = full.substring(2, 4);
  const b = full.substring(4, 6);
  return `&H${b}${g}${r}&`.toUpperCase();
}

export function exportAss(
  segments: CaptionSegment[],
  style: CaptionStyle,
  width = 1080,
  height = 1920,
  offsetSec = 0
): string {
  const scale = height / 1920;
  const fontSize = Math.round((style.fontSize || 76) * scale);
  const primaryCol = hexToAssColor(style.textColor || '#FFFFFF', 1.0);
  const outlineCol = hexToAssColor(style.outlineColor || '#000000', 1.0);
  const backCol = hexToAssColor(style.shadowColor || '#000000', 0.8);
  const outlineWidth = style.outlineWidth ? Math.round(style.outlineWidth * scale) : 0;
  const shadowDepth = style.shadow ? Math.round((style.shadowDepth || 4) * scale) : 0;
  const posX = Math.round(width * ((style.positionX ?? 50) / 100));
  const posY = Math.round(height * ((style.positionY ?? 72) / 100));
  const rot = style.rotation ? -style.rotation : 0;

  const boldVal = style.bold !== false ? -1 : 0;
  const italicVal = style.italic ? -1 : 0;
  const underlineVal = style.underline ? -1 : 0;
  const borderStyleVal = style.background ? 3 : 1;
  const alignNum = style.textAlign === 'left' ? 4 : style.textAlign === 'right' ? 6 : 5;

  const header = `[Script Info]
ScriptType: v4.00+
PlayResX: ${width}
PlayResY: ${height}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${style.fontFamily || 'Inter'},${fontSize},${primaryCol},&H000000FF,${outlineCol},${backCol},${boldVal},${italicVal},${underlineVal},0,100,100,${style.letterSpacing || 0},${rot},${borderStyleVal},${outlineWidth},${shadowDepth},${alignNum},40,40,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  const groups = buildGroups(segments, style.wordsPerLine || 3);
  const events: string[] = [];
  const textColTag = hexToAssInlineColor(style.textColor || '#FFFFFF');
  const activeColTag = hexToAssInlineColor(style.activeColor || '#FFE600');
  const kwColTag = hexToAssInlineColor(style.keywordColor || '#4CD7F6');

  for (const group of groups) {
    const start = Math.max(0, group.start - offsetSec);
    const end = Math.max(start + 0.1, group.end - offsetSec);

    if (style.animation === 'karaoke') {
      for (let i = 0; i < group.words.length; i++) {
        const wStart = i === 0 ? start : Math.max(start, group.words[i].s - offsetSec);
        const wEnd = i + 1 < group.words.length ? Math.max(wStart + 0.05, group.words[i + 1].s - offsetSec) : end;
        const lineText = group.words.map((w, idx) => {
          const txt = style.uppercase ? w.w.toUpperCase() : w.w;
          if (idx === i) return `{\\c${activeColTag}}${txt}{\\c${textColTag}}`;
          if (w.hl && style.highlightKeywords) return `{\\c${kwColTag}}${txt}{\\c${textColTag}}`;
          return txt;
        }).join(' ');
        events.push(`Dialogue: 0,${formatAssTime(wStart)},${formatAssTime(wEnd)},Default,,0,0,0,,{\\pos(${posX},${posY})}${lineText}`);
      }
    } else {
      const lineText = group.words.map((w) => {
        const txt = style.uppercase ? w.w.toUpperCase() : w.w;
        if (w.hl && style.highlightKeywords) return `{\\c${kwColTag}}${txt}{\\c${textColTag}}`;
        return txt;
      }).join(' ');
      const animTag = style.animation === 'pop' ? '{\\fscx85\\fscy85\\t(0,100,\\fscx100\\fscy100)}' : '';
      events.push(`Dialogue: 0,${formatAssTime(start)},${formatAssTime(end)},Default,,0,0,0,,{\\pos(${posX},${posY})}${animTag}${lineText}`);
    }
  }

  return header + events.join('\n') + '\n';
}

/**
 * Format detik ke format waktu SubRip (.SRT): HH:MM:SS,mmm
 */
export function formatSrtTime(sec: number): string {
  const totalMs = Math.max(0, Math.round(sec * 1000));
  const hours = Math.floor(totalMs / 3600000);
  const minutes = Math.floor((totalMs % 3600000) / 60000);
  const seconds = Math.floor((totalMs % 60000) / 1000);
  const ms = totalMs % 1000;
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')},${String(ms).padStart(3, '0')}`;
}

/**
 * Ekspor teks subtitle ke format standar SRT (SubRip) untuk DaVinci Resolve, Premiere Pro, atau CapCut.
 */
export function generateSrtContent(segments: CaptionSegment[], offsetSec: number = 0): string {
  const sorted = [...(segments || [])].sort((a, b) => a.start - b.start);
  return sorted
    .map((seg, idx) => {
      const start = Math.max(0, seg.start - offsetSec);
      const end = Math.max(start + 0.1, seg.end - offsetSec);
      return `${idx + 1}\n${formatSrtTime(start)} --> ${formatSrtTime(end)}\n${seg.text.trim()}\n`;
    })
    .join('\n');
}

/**
 * Trigger download file teks (SRT, ASS, TXT) langsung di browser.
 */
export function downloadBlob(content: string, filename: string, mimeType: string = 'text/plain'): void {
  if (typeof window === 'undefined') return;
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
