export function getVideoFilterCss(frame: FrameSettings): string {
  const parts: string[] = [];

  // 1. Basic Grading Sliders
  const br = frame.brightness ?? 1.0;
  const co = frame.contrast ?? 1.0;
  const sa = frame.saturation ?? 1.0;
  if (br !== 1.0) parts.push(`brightness(${br})`);
  if (co !== 1.0) parts.push(`contrast(${co})`);
  if (sa !== 1.0) parts.push(`saturate(${sa})`);

  // 2. Preset Filter (LUT)
  const preset = FILTER_PRESETS.find((p) => p.id === frame.filterPreset);
  if (preset && preset.id !== 'none') {
    const intensity = frame.filterIntensity ?? 100;
    const filterString = preset.cssFilter(intensity);
    if (filterString) parts.push(filterString);
  }

  // 3. OpenCut Gaussian Blur on video
  if (frame.videoBlur && frame.videoBlur > 0) {
    parts.push(`blur(${frame.videoBlur}px)`);
  }

  return parts.length > 0 ? parts.join(' ') : 'none';
}

